import os
import re
import json
from dotenv import load_dotenv
from google import genai
from google.genai import types

load_dotenv()

def extract_python_code(text: str) -> str:
    """
    Extracts raw Python code from an LLM response string.
    Strips markdown code blocks (e.g. ```python ... ``` or ``` ... ```)
    and removes any conversational text.
    """
    pattern = r"```(?:python|py)?\s*([\s\S]*?)\s*```"
    matches = re.findall(pattern, text, re.IGNORECASE)
    if matches:
        return "\n\n".join(m.strip() for m in matches).strip()
    return text.strip()

def generate_skidl_code(spec: dict, model: str = None) -> str:
    """
    Takes the JSON circuit specification generated by Phase 1 and uses Gemini
    to generate valid Python SKiDL code to model and wire the circuit.
    
    Args:
        spec: Dictionary containing circuit specifications (topology, vin_min, vin_max, vout, iout_max, fsw, mode).
        model: Optional model identifier. Defaults to env SKIDL_MODEL or 'gemini-3.5-flash'.

    Returns:
        Clean, executable Python SKiDL code as a string.
    """
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY is not set in the environment.")

    client = genai.Client(api_key=api_key)
    selected_model = model or os.environ.get("SKIDL_MODEL", "gemini-3.5-flash")
    
    spec_json_str = json.dumps(spec, indent=2)
    
    system_instruction = """
You are an expert power electronics design engineer and Python SKiDL specialist.
Your task is to take a power converter specification and write clean, valid, and fully-wired Python SKiDL code that models the schematic.

Follow these strict design rules:
1. Imports and Setup:
   - Always include KiCad symbol directory configuration at the top:
     import os
     kicad_sym_path = os.environ.get("KICAD_SYMBOL_DIR", r"D:\\Kicad\\share\\kicad\\symbols")
     for var in ['KICAD_SYMBOL_DIR', 'KICAD8_SYMBOL_DIR', 'KICAD10_SYMBOL_DIR']:
         os.environ[var] = kicad_sym_path
     from skidl import *

2. Component Selection & Footprints (Assign standard footprints to eliminate netlist errors):
   - DC Input Source: `Part('Device', 'Battery', value=f"{vin}V", footprint='Connector_PinHeader_2.54mm:PinHeader_1x02_P2.54mm_Vertical')` (pins: '+', '-')
   - Active Switch (MOSFET): `Part('Device', 'Q_NMOS', footprint='Package_TO_SOT_SMD:TO-252-2')` (pins: 'D', 'G', 'S')
   - Diode (Freewheeling): `Part('Device', 'D_Schottky', footprint='Diode_SMD:D_SMA')` (pins: 'K', 'A')
   - Inductor: `Part('Device', 'L', value=..., footprint='Inductor_SMD:L_12x12mm_h6mm')` (pins: 1, 2)
   - Filter Capacitor: `Part('Device', 'C', value=..., footprint='Capacitor_SMD:C_1206_3216Metric')` (pins: 1, 2)
   - Load Resistor: `Part('Device', 'R', value=..., footprint='Resistor_SMD:R_0805_2012Metric')` (pins: 1, 2)
   - Gate Resistor: `Part('Device', 'R', value='10k', footprint='Resistor_SMD:R_0805_2012Metric')` (pull-down connected between Gate and GND to avoid floating gate warnings in ERC)

3. Sizing Calculations:
   - Include equations in Python comments calculating nominal L, C, and R_load values based on Vin_nom, Vout, Iout_max, and fsw.

4. Net Definitions & ERC Power Drive Flags:
   - Define nets: `vin_net = Net('VIN')`, `gnd_net = Net('GND')`, `sw_net = Net('SW')`, `vout_net = Net('VOUT')`, `gate_net = Net('GATE')`.
   - Set `.drive = POWER` on driving rails (`vin_net.drive = POWER`, `gnd_net.drive = POWER`, `gate_net.drive = POWER`) so Electrical Rules Check (ERC) passes without warning.

5. Pin Wiring:
   - Connect all pins cleanly for the topology.
   - For Buck:
     * v_in['+'] += vin_net, v_in['-'] += gnd_net
     * q_main['G'] += gate_net, q_main['D'] += vin_net, q_main['S'] += sw_net
     * r_gate[1] += gate_net, r_gate[2] += gnd_net
     * d_freewheel['K'] += sw_net, d_freewheel['A'] += gnd_net
     * l_filter[1] += sw_net, l_filter[2] += vout_net
     * c_filter[1] += vout_net, c_filter[2] += gnd_net
     * r_load[1] += vout_net, r_load[2] += gnd_net

6. Verification / Netlist:
   - Always call `ERC()` and `generate_netlist(file_="circuit.net")` at the end.

7. Output Format:
   - Output ONLY the raw Python code.
"""

    prompt = f"""Generate valid Python SKiDL code for the following power circuit specification:
{spec_json_str}
"""

    response = client.models.generate_content(
        model=selected_model,
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=system_instruction,
            temperature=0.2,
        ),
    )

    raw_output = response.text or ""
    cleaned_code = extract_python_code(raw_output)
    return cleaned_code
